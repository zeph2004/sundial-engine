class NumberedLandscapeCanvas(pdf_canvas.Canvas):
    """Canvas subclass that stamps 'Generated by Sundial Engine · <date>' and 'Page X of Y'."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        self._generated_date = kwargs.pop("generated_date", "")
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_footer(num_pages)
            super().showPage()
        super().save()

    def _draw_footer(self, page_count: int) -> None:
        page_w, _ = landscape(A4)
        margin_x = 10 * mm
        footer_y = 7 * mm

        self.saveState()
        self.setStrokeColor(COL_DUST)
        self.setLineWidth(0.5)
        self.line(margin_x, footer_y + 3.5 * mm, page_w - margin_x, footer_y + 3.5 * mm)

        self.setFont("Helvetica", 7.5)
        self.setFillColor(COL_SLATE)
        left_text = f"Generated by Sundial Engine · {self._generated_date}"
        self.drawString(margin_x, footer_y, left_text)

        right_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(page_w - margin_x, footer_y, right_text)
        self.restoreState()


def sanitize_filename(raw: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", str(raw or "timetable").strip())
    return cleaned.strip("._") or "timetable"


def _format_date(iso_str: Optional[str]) -> str:
    if iso_str:
        try:
            dt = datetime.fromisoformat(iso_str.replace("Z", "+00:00"))
            return dt.strftime("%d %b %Y")
        except Exception:
            pass
    return datetime.now(timezone.utc).strftime("%d %b %Y")


def _extract_period_lookup(state: Dict[str, Any]) -> Dict[int, Tuple[str, str]]:
    lookup: Dict[int, Tuple[str, str]] = {}
    for p in state.get("teaching_periods", []):
        try:
            pnum = int(p.get("period", p.get("period_number", 0)))
            if pnum > 0:
                lookup[pnum] = (
                    str(p.get("start", p.get("start_time", ""))),
                    str(p.get("end", p.get("end_time", ""))),
                )
        except Exception:
            continue

    schema_periods = state.get("schema", {}).get("calendar_grid", {}).get("periods")
    if isinstance(schema_periods, list):
        for p in schema_periods:
            try:
                pnum = int(p.get("period_number", p.get("period", 0)))
                if pnum > 0:
                    lookup[pnum] = (
                        str(p.get("start_time", p.get("start", ""))),
                        str(p.get("end_time", p.get("end", ""))),
                    )
            except Exception:
                continue
    return lookup


def _resolve_entities(
    state: Dict[str, Any],
    scheduled_sessions: List[Dict[str, Any]],
    lens: str,
) -> List[Tuple[str, str, List[Dict[str, Any]]]]:
    """Returns sorted [(entity_id, display_title, entity_sessions), ...] for the lens."""
    if lens == "cohort":
        by_id: Dict[str, List[Dict[str, Any]]] = {}
        for s in scheduled_sessions:
            for c in s.get("cohorts", []):
                by_id.setdefault(c, []).append(s)
        results: List[Tuple[str, str, List[Dict[str, Any]]]] = []
        for cid in sorted(by_id.keys(), key=lambda x: x.lower()):
            sess = by_id[cid]
            has_ft = any(not s.get("is_evening_stream") for s in sess)
            has_eve = any(s.get("is_evening_stream") for s in sess)
            stream_lbl = (
                "Full-Time & Evening"
                if (has_ft and has_eve)
                else ("Evening" if has_eve else "Full-Time")
            )
            results.append((cid, f"Cohort: {cid} ({stream_lbl})", sess))
        return results

    if lens == "lecturer":
        by_id = {}
        for s in scheduled_sessions:
            for lec in s.get("lecturers", []):
                by_id.setdefault(lec, []).append(s)
        return [
            (lid, f"Lecturer: {lid}", by_id[lid])
            for lid in sorted(by_id.keys(), key=lambda x: x.lower())
        ]

    # lens == "venue"
    venue_names: Dict[str, str] = {
        str(v.get("venueId")): f"{v.get('name', v.get('venueId'))} ({v.get('category', 'Venue')})"
        for v in state.get("venues", [])
    }
    by_id = {}
    for s in scheduled_sessions:
        vid = str(s.get("venue_id"))
        by_id.setdefault(vid, []).append(s)

    results = []
    for vid in by_id.keys():
        label = venue_names.get(vid, f"Venue {vid}")
        results.append((vid, f"Venue: {label}", by_id[vid]))
    results.sort(key=lambda item: item[1].lower())
    return results


def _determine_visible_periods(
    entity_sessions: List[Dict[str, Any]],
    schema: Dict[str, Any],
) -> List[int]:
    grid = schema.get("calendar_grid", {})
    streams = schema.get("streams", {})
    ft_cfg = streams.get("full_time", {})
    eve_cfg = streams.get("evening", {})
    twi_cfg = eve_cfg.get("twilight_buffer", {})

    total_p = int(grid.get("periods_per_day", 18))
    ft_min = int(ft_cfg.get("min_period", 1))
    ft_max = int(ft_cfg.get("max_period", 12))
    eve_min = int(eve_cfg.get("min_period", 13))
    eve_max = int(eve_cfg.get("max_period", total_p))
    twi_min = (
        int(twi_cfg.get("buffer_min_period", 11))
        if twi_cfg.get("enabled", True)
        else eve_min
    )

    has_ft = any(not s.get("is_evening_stream") for s in entity_sessions)
    has_eve = any(s.get("is_evening_stream") for s in entity_sessions)

    if has_ft and not has_eve:
        lo, hi = ft_min, ft_max
    elif has_eve and not has_ft:
        lo, hi = min(eve_min, twi_min), eve_max
    else:
        lo, hi = 1, total_p

    # Ensure every placed session fits inside [lo, hi]
    for s in entity_sessions:
        sp = int(s.get("start_period", 1))
        ep = sp + int(s.get("duration_periods", 1)) - 1
        lo = min(lo, sp)
        hi = max(hi, ep)

    return list(range(max(1, lo), min(total_p, hi) + 1))


def _load_logo_flowable(logo_path: Optional[Path]) -> Optional[Any]:
    if not logo_path or not logo_path.exists() or not logo_path.is_file():
        return None
    if logo_path.suffix.lower() not in {".png", ".jpg", ".jpeg", ".webp"}:
        return None
    try:
        from reportlab.platypus import Image as RLImage

        reader = ImageReader(str(logo_path))
        iw, ih = reader.getSize()
        if iw <= 0 or ih <= 0:
            return None
        max_h = 11 * mm
        max_w = 26 * mm
        scale = min(max_h / ih, max_w / iw)
        return RLImage(str(logo_path), width=iw * scale, height=ih * scale)
    except Exception:
        return None


def merge_adjacent_sessions(
    day_sessions: List[Dict[str, Any]],
    break_slots: set[int],
) -> List[Dict[str, Any]]:
    """
    Visually merges immediately adjacent identical sessions on the same day
    (same module_code, session_type, venue_id, lecturers, cohorts) when there
    is no break boundary between them.
    """
    ordered = sorted(day_sessions, key=lambda s: int(s.get("start_period", 1)))
    merged: List[Dict[str, Any]] = []
    for s in ordered:
        sp = int(s.get("start_period", 1))
        dur = int(s.get("duration_periods", 1))
        if merged:
            prev = merged[-1]
            prev_sp = int(prev.get("start_period", 1))
            prev_dur = int(prev.get("duration_periods", 1))
            prev_end = prev_sp + prev_dur - 1
            same_identity = (
                str(prev.get("module_code", "")) == str(s.get("module_code", ""))
                and str(prev.get("session_type", "")) == str(s.get("session_type", ""))
                and str(prev.get("venue_id", "")) == str(s.get("venue_id", ""))
                and sorted(prev.get("lecturers", [])) == sorted(s.get("lecturers", []))
                and sorted(prev.get("cohorts", [])) == sorted(s.get("cohorts", []))
            )
            if prev_sp + prev_dur == sp and prev_end not in break_slots and same_identity:
                prev["duration_periods"] = prev_dur + dur
                continue
        merged.append(dict(s))
    return merged


def _build_entity_story(
    entity_title: str,
    entity_sessions: List[Dict[str, Any]],
    lens: str,
    state: Dict[str, Any],
    logo_path: Optional[Path],
    usable_width: float,
) -> List[Any]:
    branding = state.get("branding") or DEFAULT_BRANDING
    inst_name = str(branding.get("institution_name") or DEFAULT_BRANDING["institution_name"])
    sem_title = str(branding.get("semester_title") or DEFAULT_BRANDING["semester_title"])
    schema = state.get("schema", {})
    grid = schema.get("calendar_grid", {})
    active_days = list(grid.get("active_days", ["MONDAY", "TUESDAY", "WEDNESDAY", "THURSDAY", "FRIDAY", "SATURDAY"]))
    break_slots = set(grid.get("breaks_after_periods", [4, 6]))
    period_lookup = _extract_period_lookup(state)

    # Omit SATURDAY if this entity has 0 Saturday sessions
    has_sat = any(s.get("day") == "SATURDAY" for s in entity_sessions)
    visible_days = [d for d in active_days if d != "SATURDAY" or has_sat]
    if not visible_days:
        visible_days = active_days[:5]

    visible_periods = _determine_visible_periods(entity_sessions, schema)

    # Styles
    inst_style = ParagraphStyle(
        "InstTitle",
        fontName="Helvetica-Bold",
        fontSize=12.5,
        leading=14.5,
        textColor=COL_SHADOW,
    )
    sem_style = ParagraphStyle(
        "SemTitle",
        fontName="Helvetica",
        fontSize=8.5,
        leading=10.5,
        textColor=COL_SLATE,
    )
    entity_style = ParagraphStyle(
        "EntityTitle",
        fontName="Helvetica-Bold",
        fontSize=11.5,
        leading=13.5,
        alignment=2,  # right
        textColor=COL_INDIGO,
    )
    th_style = ParagraphStyle(
        "TH",
        fontName="Helvetica-Bold",
        fontSize=7.5,
        leading=9,
        alignment=1,
        textColor=COL_SHADOW,
    )
    th_time_style = ParagraphStyle(
        "THTime",
        fontName="Helvetica",
        fontSize=6.2,
        leading=7.5,
        alignment=1,
        textColor=COL_SLATE,
    )
    day_style = ParagraphStyle(
        "DayCell",
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=10,
        textColor=COL_SHADOW,
    )
    cell_font_size = 6.6 if len(visible_periods) <= 12 else 5.8
    cell_leading = 7.8 if len(visible_periods) <= 12 else 6.8
    cell_style = ParagraphStyle(
        "SessionCell",
        fontName="Helvetica",
        fontSize=cell_font_size,
        leading=cell_leading,
        textColor=COL_SHADOW,
    )

    # 1. Noticeboard Header Block (clean entity title only on right)
    logo_img = _load_logo_flowable(logo_path)
    left_block = [
        Paragraph(escape(inst_name), inst_style),
        Paragraph(escape(sem_title), sem_style),
    ]
    right_block = [
        Paragraph(escape(entity_title), entity_style),
    ]

    if logo_img is not None:
        header_table = Table(
            [[logo_img, left_block, right_block]],
            colWidths=[28 * mm, usable_width * 0.48 - 28 * mm, usable_width * 0.52],
        )
    else:
        header_table = Table(
            [[left_block, right_block]],
            colWidths=[usable_width * 0.50, usable_width * 0.50],
        )

    header_table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ("TOPPADDING", (0, 0), (-1, -1), 0),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LINEBELOW", (0, 0), (-1, 0), 1.0, COL_SHADOW),
            ]
        )
    )

    # 2. Build Column Specs (inserting dedicated narrow break columns after break periods)
    # Each spec is ("period", period_num, "") or ("break", after_period_num, "TEA"|"LUNCH"|"BREAK")
    col_specs: List[Tuple[str, int, str]] = []
    for idx, p in enumerate(visible_periods):
        col_specs.append(("period", p, ""))
        if p in break_slots and idx < len(visible_periods) - 1:
            brk_label = "TEA" if p == 4 else ("LUNCH" if p == 6 else "BREAK")
            col_specs.append(("break", p, brk_label))

    day_col_w = 16 * mm
    break_col_w = 20.0  # 20pt narrow break column
    num_breaks = sum(1 for kind, _, _ in col_specs if kind == "break")
    period_col_w = (
        usable_width - day_col_w - num_breaks * break_col_w
    ) / max(1, len(visible_periods))
    col_widths = [day_col_w] + [
        break_col_w if kind == "break" else period_col_w for kind, _, _ in col_specs
    ]

    header_row: List[Any] = [Paragraph("<b>Day</b>", th_style)]
    for kind, p, _label in col_specs:
        if kind == "break":
            header_row.append("")
        else:
            times = period_lookup.get(p)
            time_line = f"{times[0]}–{times[1]}" if times and times[0] else ""
            header_row.append(
                [
                    Paragraph(f"P{p}", th_style),
                    Paragraph(time_line, th_time_style) if time_line else Spacer(1, 1),
                ]
            )

    table_data: List[List[Any]] = [header_row]
    style_cmds: List[Tuple[Any, ...]] = [
        ("BOX", (0, 0), (-1, -1), 0.75, COL_SHADOW),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, COL_DUST),
        ("BACKGROUND", (0, 0), (-1, 0), COL_STONE),
        ("LINEBELOW", (0, 0), (-1, 0), 0.75, COL_SHADOW),
        ("LINEAFTER", (0, 0), (0, -1), 0.75, COL_SHADOW),
        ("VALIGN", (0, 0), (-1, 0), "MIDDLE"),
        ("VALIGN", (0, 1), (0, -1), "MIDDLE"),
        ("VALIGN", (1, 1), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 3),
        ("RIGHTPADDING", (0, 0), (-1, -1), 3),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]

    period_to_col: Dict[int, int] = {}
    break_col_indices: Dict[int, str] = {}
    for idx, (kind, p, label) in enumerate(col_specs):
        col_idx = idx + 1
        if kind == "period":
            period_to_col[p] = col_idx
        else:
            break_col_indices[col_idx] = label

    num_days = len(visible_days)
    for r_offset, day in enumerate(visible_days):
        row_idx = r_offset + 1
        day_sess = merge_adjacent_sessions(
            [s for s in entity_sessions if s.get("day") == day],
            break_slots,
        )
        day_periods = sum(int(s.get("duration_periods", 1)) for s in day_sess)
        day_label = f"{SHORT_DAY.get(day, day[:3])}<br/><font size='6.5' color='#5A6272'>{day_periods}p</font>"

        row_cells: List[Any] = [Paragraph(day_label, day_style)] + [""] * len(col_specs)
        style_cmds.append(("BACKGROUND", (0, row_idx), (0, row_idx), COL_STONE))

        # Place rotated break label on first day row (will be spanned vertically across all days)
        if r_offset == 0:
            for b_col, b_label in break_col_indices.items():
                row_cells[b_col] = VerticalBreakLabel(b_label, font_size=7.5)

        occupied_cols: set[int] = set(break_col_indices.keys())
        for s in day_sess:
            sp = int(s.get("start_period", 1))
            dur = int(s.get("duration_periods", 1))
            ep = sp + dur - 1
            if sp not in period_to_col:
                continue
            start_col = period_to_col[sp]
            end_col = period_to_col.get(ep, start_col)
            if end_col < start_col:
                end_col = start_col

            mod_code = escape(str(s.get("module_code", "")))
            stype = escape(str(s.get("session_type", "Theory")))
            lecturers_str = escape(", ".join(s.get("lecturers", [])) or "TBA")
            venue_str = escape(str(s.get("venue_name", "")))
            cohorts_str = escape(", ".join(s.get("cohorts", [])))

            if lens == "cohort":
                cell_html = (
                    f"<b>{mod_code}</b><br/>"
                    f"{lecturers_str}<br/>"
                    f"{venue_str}<br/>"
                    f"<font color='#5A6272'>{stype}</font>"
                )
            elif lens == "venue":
                cell_html = (
                    f"<b>{mod_code}</b><br/>"
                    f"{lecturers_str}<br/>"
                    f"{cohorts_str}<br/>"
                    f"<font color='#5A6272'>{stype}</font>"
                )
            else:  # lecturer lens
                cell_html = (
                    f"<b>{mod_code}</b><br/>"
                    f"{cohorts_str}<br/>"
                    f"{venue_str}<br/>"
                    f"<font color='#5A6272'>{stype}</font>"
                )

            p_elem = Paragraph(cell_html, cell_style)

            if start_col not in occupied_cols:
                row_cells[start_col] = p_elem
                span_end = start_col
                for c in range(start_col + 1, end_col + 1):
                    if c not in occupied_cols:
                        span_end = c
                    else:
                        break
                for c in range(start_col, span_end + 1):
                    occupied_cols.add(c)
                if span_end > start_col:
                    style_cmds.append(("SPAN", (start_col, row_idx), (span_end, row_idx)))
                bg = COL_DUSK if s.get("is_evening_stream") else COL_DAYBREAK
                style_cmds.append(("BACKGROUND", (start_col, row_idx), (span_end, row_idx), bg))
            else:
                existing = row_cells[start_col]
                if isinstance(existing, list):
                    existing.append(Spacer(1, 2))
                    existing.append(p_elem)
                elif existing != "":
                    row_cells[start_col] = [existing, Spacer(1, 2), p_elem]
                else:
                    row_cells[start_col] = p_elem

        table_data.append(row_cells)

    # Style and vertically span dedicated Tea / Lunch break columns
    for b_col in break_col_indices:
        style_cmds.append(("BACKGROUND", (b_col, 0), (b_col, num_days), COL_BREAK))
        style_cmds.append(("LINEBEFORE", (b_col, 0), (b_col, num_days), 0.75, COL_SHADOW))
        style_cmds.append(("LINEAFTER", (b_col, 0), (b_col, num_days), 0.75, COL_SHADOW))
        style_cmds.append(("ALIGN", (b_col, 1), (b_col, num_days), "CENTER"))
        style_cmds.append(("VALIGN", (b_col, 1), (b_col, num_days), "MIDDLE"))
        style_cmds.append(("LEFTPADDING", (b_col, 0), (b_col, num_days), 0))
        style_cmds.append(("RIGHTPADDING", (b_col, 0), (b_col, num_days), 0))
        if num_days > 1:
            style_cmds.append(("SPAN", (b_col, 1), (b_col, num_days)))

    # Comfortable row heights so 4-line session cells fit cleanly on landscape A4
    data_row_h = min(26 * mm, max(19 * mm, (148 * mm) / max(1, num_days)))
    row_heights = [11 * mm] + [data_row_h] * num_days

    grid_table = Table(table_data, colWidths=col_widths, rowHeights=row_heights)
    grid_table.setStyle(TableStyle(style_cmds))

    return [header_table, Spacer(1, 4 * mm), grid_table]


def _render_pdf_bytes(
    story: List[Any],
    generated_date: str,
) -> bytes:
    buf = io.BytesIO()
    page_w, page_h = landscape(A4)
    doc = SimpleDocTemplate(
        buf,
        pagesize=(page_w, page_h),
        leftMargin=10 * mm,
        rightMargin=10 * mm,
        topMargin=9 * mm,
        bottomMargin=13 * mm,
        title="Sundial University Timetable",
        author="Sundial Engine",
    )
    doc.build(
        story,
        canvasmaker=lambda *a, **kw: NumberedLandscapeCanvas(
            *a, generated_date=generated_date, **kw
        ),
    )
    return buf.getvalue()


def render_single_timetable_pdf(
    state: Dict[str, Any],
    lens: str,
    entity_id: str,
    logo_path: Optional[Path] = None,
) -> bytes:
    """Renders a single-page A4 Landscape noticeboard PDF for one cohort, lecturer, or venue."""
    lens_norm = lens.strip().lower()
    if lens_norm not in VALID_LENSES:
        raise ValueError(f"Invalid lens '{lens}'. Expected one of {VALID_LENSES}.")

    assignments = state.get("assignments") or {}
    if not assignments:
        raise KeyError("No active timetable has been generated yet.")

    scheduled = build_public_sessions_list(
        sessions=state.get("sessions", []),
        assignments=assignments,
        pinned_ids=set((state.get("pinned_assignments") or {}).keys()),
    )
    entities = _resolve_entities(state, scheduled, lens_norm)

    target_norm = str(entity_id).strip()
    matched = None
    for eid, title, sess in entities:
        if eid == target_norm or eid.lower() == target_norm.lower():
            matched = (eid, title, sess)
            break

    if matched is None:
        raise KeyError(f"{lens_norm.capitalize()} '{entity_id}' was not found in the active timetable.")

    page_w, _ = landscape(A4)
    usable_w = page_w - 20 * mm
    story = _build_entity_story(
        entity_title=matched[1],
        entity_sessions=matched[2],
        lens=lens_norm,
        state=state,
        logo_path=logo_path,
        usable_width=usable_w,
    )
    gen_date = _format_date(
        (state.get("active_timetable") or {}).get("generated_at") or state.get("updated_at")
    )
    return _render_pdf_bytes(story, generated_date=gen_date)


def render_master_timetable_pdf(
    state: Dict[str, Any],
    lens: str = "cohort",
    logo_path: Optional[Path] = None,
) -> bytes:
    """Renders a multi-page A4 Landscape noticeboard PDF (one entity per page, sorted alphabetically)."""
    lens_norm = lens.strip().lower()
    if lens_norm not in VALID_LENSES:
        raise ValueError(f"Invalid lens '{lens}'. Expected one of {VALID_LENSES}.")

    assignments = state.get("assignments") or {}
    if not assignments:
        raise KeyError("No active timetable has been generated yet.")

    scheduled = build_public_sessions_list(
        sessions=state.get("sessions", []),
        assignments=assignments,
        pinned_ids=set((state.get("pinned_assignments") or {}).keys()),
    )
    entities = [
        item for item in _resolve_entities(state, scheduled, lens_norm) if len(item[2]) > 0
    ]
    if not entities:
        raise KeyError(f"No {lens_norm} timetables with scheduled sessions were found.")

    page_w, _ = landscape(A4)
    usable_w = page_w - 20 * mm
    story: List[Any] = []
    for idx, (_eid, title, sess) in enumerate(entities):
        if idx > 0:
            story.append(PageBreak())
        story.extend(
            _build_entity_story(
                entity_title=title,
                entity_sessions=sess,
                lens=lens_norm,
                state=state,
                logo_path=logo_path,
                usable_width=usable_w,
            )
        )

    gen_date = _format_date(
        (state.get("active_timetable") or {}).get("generated_at") or state.get("updated_at")
    )
    return _render_pdf_bytes(story, generated_date=gen_date)
