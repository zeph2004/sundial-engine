class VerticalBreakLabel(Flowable):
    """Crisp vertically rotated label ('TEA' / 'LUNCH') centered inside a narrow break column."""

    def __init__(self, text: str, font_size: float = 7.5) -> None:
        super().__init__()
        self.text = text
        self.font_size = font_size
        self.width = font_size + 4
        self.height = max(24.0, len(text) * (font_size * 0.72) + 8.0)

    def draw(self) -> None:
        self.canv.saveState()
        self.canv.setFont("Helvetica-Bold", self.font_size)
        self.canv.setFillColor(COL_SLATE)
        self.canv.translate(self.width / 2.0 + self.font_size * 0.34, self.height / 2.0)
        self.canv.rotate(90)
        self.canv.drawCentredString(0, 0, self.text)
        self.canv.restoreState()

